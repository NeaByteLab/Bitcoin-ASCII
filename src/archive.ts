import NodeFS from 'node:fs'
import NodePath from 'node:path'
import NodeProcess from 'node:process'
import Chart from '@app/chart.ts'
import Price from '@app/price.ts'
import type * as Types from '@app/types.ts'

export default class Archive {
  static async generateArchive(date: Date): Promise<string> {
    console.log(`Generating archive for ${date.toDateString()}...`)
    const candlesticks = await Price.getHistoricalData(date)
    if (candlesticks.length === 0) {
      throw new Error(`No candlestick data available for ${date.toDateString()}`)
    }
    const chart = Chart.generateCleanChart(candlesticks, 48)
    const stats = Archive.calculateArchiveStats(candlesticks)
    const content = Archive.generateArchiveContent(date, chart, stats)
    const archivePath = Archive.getArchivePath(date)
    NodeFS.mkdirSync(NodePath.join(archivePath, '..'), { recursive: true })
    NodeFS.writeFileSync(archivePath, content, 'utf8')
    console.log(`✓ Archive generated: ${archivePath}`)
    return archivePath
  }

  private static calculateArchiveStats(candlesticks: Types.CandlestickData[]): Types.ArchiveStats {
    const first = candlesticks[0]
    const last = candlesticks[candlesticks.length - 1]
    if (!first || !last) {
      throw new Error('No candlestick data available for statistics calculation')
    }
    const prices = candlesticks.map((c) => c.closePrice)
    if (prices.some((price) => isNaN(price) || price < 0)) {
      throw new Error('Invalid price data in candlesticks')
    }
    const openPrice = first.openPrice
    const closePrice = last.closePrice
    if (isNaN(openPrice) || isNaN(closePrice) || openPrice <= 0) {
      throw new Error('Invalid open/close prices for change calculation')
    }
    const highPrice = Math.max(...candlesticks.map((c) => c.highPrice))
    const lowPrice = Math.min(...candlesticks.map((c) => c.lowPrice))
    const priceChange = closePrice - openPrice
    const changePercent = (priceChange / openPrice) * 100
    const totalVolume = candlesticks.reduce((sum, c) => sum + (c.tradeVolume ?? 0), 0)
    const avgPrice = prices.reduce((sum, price) => sum + price, 0) / prices.length
    return {
      highPrice,
      lowPrice,
      openPrice,
      closePrice,
      priceChange,
      changePercent,
      totalVolume,
      avgPrice
    }
  }

  private static generateArchiveContent(
    date: Date,
    chart: string,
    stats: Types.ArchiveStats
  ): string {
    const changeEmoji = stats.changePercent >= 0 ? '🟢' : '🔴'
    const changeSign = stats.changePercent >= 0 ? '+' : ''
    return `# Bitcoin Archive - ${date.toDateString()} 📊

## 📈 24-Hour Bitcoin Chart (30m intervals)

\`\`\`
${chart}
\`\`\`

## 📊 Daily Statistics

| Metric | Value |
|--------|-------|
| Date | ${date.toDateString()} |
| Open | $${stats.openPrice.toLocaleString()} |
| Close | $${stats.closePrice.toLocaleString()} |
| High | $${stats.highPrice.toLocaleString()} |
| Low | $${stats.lowPrice.toLocaleString()} |
| Change | ${changeEmoji} ${changeSign}$${stats.priceChange.toFixed(2)} |
| Change % | ${changeEmoji} ${changeSign}${stats.changePercent.toFixed(2)}% |
| Volume | $${(stats.totalVolume / 1e6).toFixed(2)}M |
| Avg Price | $${stats.avgPrice.toLocaleString()} |

## 📅 Trading Session

- **Period:** 24 hours (48 x 30-minute intervals)
- **Data Source:** Binance Futures API

---
*Generated by Bitcoin-ASCII Archive System*
`
  }

  private static getArchivePath(date: Date): string {
    const year = date.getFullYear()
    const month = String(date.getMonth() + 1).padStart(2, '0')
    const day = String(date.getDate()).padStart(2, '0')
    return NodePath.join(NodeProcess.cwd(), 'archive', String(year), String(month), `${day}.md`)
  }
}
